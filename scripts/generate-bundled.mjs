// Regenerate src/bundled.js from the runtime bundle indexes: the packages and
// TikZ/PGF libraries the TeX engine can actually load. Run after `npm run build`.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const bundles = join(root, 'runtime/dist/bundles');
const files = new Set();
for (const bundle of readdirSync(bundles)) {
  const index = join(bundles, bundle, 'files.index.json');
  if (!existsSync(index)) continue;
  const parsed = JSON.parse(readFileSync(index, 'utf8'));
  for (const key of Object.keys(parsed.files ?? parsed)) files.add(key);
}
const base = path => path.slice(path.lastIndexOf('/') + 1);
const packages = new Set(), classes = new Set(), tikz = new Set(), pgf = new Set(), pgfplots = new Set();
for (const file of files) {
  const name = base(file);
  let match;
  if ((match = /^(.+)\.sty$/.exec(name))) packages.add(match[1].replace(/-\d{4}-\d{2}-\d{2}$/, ''));
  else if ((match = /^(.+)\.cls$/.exec(name))) classes.add(match[1]);
  else if ((match = /^tikzlibrarypgfplots\.(.+)\.code\.tex$/.exec(name))) pgfplots.add(match[1]);
  else if ((match = /^pgfplotslibrary(.+)\.code\.tex$/.exec(name))) pgfplots.add(match[1]);
  else if ((match = /^tikzlibrary(.+)\.code\.tex$/.exec(name))) tikz.add(match[1]);
  else if ((match = /^pgflibrary(.+)\.code\.tex$/.exec(name))) pgf.add(match[1]);
}
const sorted = set => [...set].sort();
const literal = set => JSON.stringify(sorted(set));
writeFileSync(join(root, 'src/bundled.js'), `// Generated by scripts/generate-bundled.mjs from runtime/dist/bundles — do not edit.
// What the bundled TeX tree can load; source normalization drops everything else.
export const BUNDLED_PACKAGES = new Set(${literal(packages)});
export const BUNDLED_CLASSES = new Set(${literal(classes)});
export const BUNDLED_TIKZ_LIBRARIES = new Set(${literal(new Set([...tikz, ...pgf]))});
export const BUNDLED_PGFPLOTS_LIBRARIES = new Set(${literal(pgfplots)});
`);
console.log(`packages ${packages.size}, classes ${classes.size}, tikz libraries ${tikz.size + pgf.size}, pgfplots libraries ${pgfplots.size}`);
